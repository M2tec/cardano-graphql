const axios = require('axios');
const fs = require('fs');
const path = require('path');

async function queryMetadata(assetIds) {
  const axiosClient = axios.create({
    baseURL: 'http://localhost:8080', // replace with your actual base URL
    headers: {
      'Content-Type': 'application/json'
    }
  });

  try {
    const response = await axiosClient.post('metadata/query', {
      subjects: assetIds,
      properties: [
        'decimals',
        'description',
        'logo',
        'name',
        'ticker',
        'url'
      ]
    });

    const metadataList = response.data;

    // Ensure the data directory exists
    const dataDir = path.join(__dirname, 'cf-data');
    if (!fs.existsSync(dataDir)) {
      fs.mkdirSync(dataDir);
    }

    // Write each object to its own file
    for (const metadata of metadataList.subjects) {
      const filePath = path.join(dataDir, `${metadata.subject}.json`);
      fs.writeFileSync(filePath, JSON.stringify(metadata, null, 2), 'utf8');
      console.log(`Saved: ${filePath}`);
    }
  } catch (error) {
    console.error('Error querying metadata:', error.message);
  }
}

